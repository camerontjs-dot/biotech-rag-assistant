"""A scripted stand-in provider for tests, examples, and offline exercise. It is not a model.

``ScriptedProvider`` returns pre-written outputs in order, records every request it receives, and
reports itself as ``scripted`` in every turn record, so its output can never be mistaken for a
live model's. It cannot be selected through environment configuration; code must construct it
explicitly and pass it to ``create_chat_app``.

A step is one of: a JSON-serialisable answer ``dict``; a raw output ``str`` (to test malformed
output); a ``ProviderError`` to raise; or a callable ``(request, payload) -> step`` that builds its
output from the passages the application actually supplied.
"""

from __future__ import annotations

import json
from collections.abc import Callable, Iterable
from typing import Any

from biotech_rag_assistant.chat.prompting import parse_payload
from biotech_rag_assistant.chat.provider import (
    ProviderAvailability,
    ProviderError,
    ProviderRequest,
    ProviderResult,
    ProviderTraceMeta,
    ProviderUsage,
)

Step = dict[str, Any] | str | ProviderError | Callable[[ProviderRequest, dict[str, Any]], Any]

SCRIPTED_MODEL = "scripted-test-double"


class ScriptedProvider:
    name = "scripted"

    def __init__(
        self,
        steps: Iterable[Step] = (),
        *,
        by_question: dict[str, Step] | None = None,
        model: str = SCRIPTED_MODEL,
    ) -> None:
        """``by_question`` maps a verbatim user message to its step; other turns use ``steps``."""
        self.model = model
        self._steps: list[Step] = list(steps)
        self._by_question = dict(by_question or {})
        self.requests: list[ProviderRequest] = []

    def push(self, *steps: Step) -> None:
        self._steps.extend(steps)

    @property
    def remaining(self) -> int:
        return len(self._steps)

    def availability(self) -> ProviderAvailability:
        return ProviderAvailability(
            available=True,
            provider=self.name,
            model=self.model,
            message="Scripted test provider: outputs are pre-written, not generated by a model.",
            store=None,
        )

    def generate(self, request: ProviderRequest) -> ProviderResult:
        self.requests.append(request)
        question = request_payload(request).get("current_question")
        if isinstance(question, str) and question in self._by_question:
            step: Step = self._by_question[question]
        elif self._steps:
            step = self._steps.pop(0)
        else:
            raise ProviderError("upstream_error", detail="scripted provider has no step left")
        while callable(step) and not isinstance(step, ProviderError):
            step = step(request, request_payload(request))
        if isinstance(step, ProviderError):
            raise step
        text = step if isinstance(step, str) else json.dumps(step)
        return ProviderResult(
            output_text=text,
            provider=self.name,
            model_requested=self.model,
            meta=ProviderTraceMeta(
                model_reported=self.model,
                response_id=f"scripted-{len(self.requests)}",
                usage=ProviderUsage(),
                latency_ms=0,
            ),
            store=None,
        )


def request_payload(request: ProviderRequest) -> dict[str, Any]:
    """The JSON payload the application put in the final user message."""
    return parse_payload(request.input[-1]["content"])


def find_passage(payload: dict[str, Any], *, doc_id: str, contains: str = "") -> dict[str, Any]:
    """The supplied passage for ``doc_id`` whose text contains ``contains``."""
    for passage in payload["passages"]:
        if passage["document"]["doc_id"] == doc_id and contains in passage["text"]:
            return passage
    raise LookupError(f"no supplied passage for {doc_id} containing {contains!r}")


def block(kind: str, text: str, *citations: tuple[str, str]) -> dict[str, Any]:
    return {
        "kind": kind,
        "text": text,
        "citations": [{"ref": ref, "quote": quote} for ref, quote in citations],
    }


def answer(
    status: str,
    blocks: list[dict[str, Any]] | None = None,
    *,
    missing: list[dict[str, Any]] | None = None,
    question: str = "",
) -> dict[str, Any]:
    return {
        "status": status,
        "blocks": blocks or [],
        "missing_information": missing or [],
        "clarifying_question": question,
    }


def missing_item(requested: str, explanation: str, *refs: str) -> dict[str, Any]:
    return {"requested": requested, "explanation": explanation, "related_refs": list(refs)}
