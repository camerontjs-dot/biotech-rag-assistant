"""docs/chat-examples.md must match a fresh replay of the scripted conversations.

The examples document is generated by replaying scripted conversations through the real chat
app, so any change to interpretation, retrieval, evidence, or checks shows up as drift here.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def test_chat_examples_document_is_current() -> None:
    result = subprocess.run(
        [sys.executable, str(ROOT / "scripts/render_chat_examples.py"), "--check"],
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=False,
    )

    assert result.returncode == 0, result.stdout + result.stderr
